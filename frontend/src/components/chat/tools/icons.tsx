/** The icon of a tool, a wrench for tools without one such as MCP tools. */
export function ToolIcon({ name }: { name: string }) {
  const Icon = isCatalogKey(TOOL_ICONS, name) ? TOOL_ICONS[name] : WrenchIcon;

  return <Icon />;
}
